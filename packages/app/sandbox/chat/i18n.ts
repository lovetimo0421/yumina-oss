const STRINGS: Record<SandboxLang, Dict> = { en, zh, ja, es, ko, id, ru };

function isTraditionalChinese(language: string | undefined): boolean {
  return /^zh[-_](hant|tw|hk|mo)(?:$|[-_])/i.test(language ?? "");
}

export type ChatStringKey = keyof typeof en;

/** Build a translator bound to the active language. Falls back to English for
 *  any key missing in the active language, then to the key itself. */
export function makeChatT(language: string | undefined) {
  const lang = pickLang(language);
  const dict = isTraditionalChinese(language) ? { ...zh, ...zhHant } : STRINGS[lang];
  return (key: ChatStringKey, vars?: Record<string, string | number>): string => {
    let s: string = pluralVariant(dict, lang, key, vars) ?? dict[key] ?? en[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(`{{${k}}}`, String(v));
      }
    }
    return s;
  };
}

