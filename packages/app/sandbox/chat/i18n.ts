/** Translator for the 提示词 / 解除限制 surfaces (same fallback rules as makeChatT). */
export function makePromptsT(language: string | undefined) {
  const lang = pickLang(language);
  const dict: Record<string, string> = /^zh[-_](hant|tw|hk|mo)/i.test(language ?? "")
    ? promptsZhHant : PROMPTS_STRINGS[lang];
  return (key: PromptsStringKey, vars?: Record<string, string | number>): string => {
    let s: string = pluralVariant(dict, lang, key, vars) ?? dict[key] ?? promptsEn[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{{${k}}}`).join(String(v));
    }
    return s;
  };
}
