/**
 * The seam: the only core files allowed to import hosted code. Two halves so
 * stores/lib never load React UI (slots.state.ts) — the export replaces each
 * with its `.local` twin.
 */
const SEAM_FILES = new Set(["edition/slots.tsx", "edition/slots.state.ts"]);

const EXTENSIONS = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".json", ".css"];

function toPosix(p) {
  return p.split(sep).join(posix.sep);
}

/** Drop the file extension only; `stores/credits.test.ts` -> `stores/credits.test`. */
function stripExt(p) {
  return p.replace(/\.(tsx?|jsx?|mjs|json|css)$/, "");
}

/** Is `rel` (posix, relative to src, with or without extension) hosted? */
export function isHostedPath(rel) {
  const bare = stripExt(rel);
  // A test sits next to the module it covers and goes wherever that goes.
  const source = bare.replace(/\.test$/, "");
  for (const dir of HOSTED_DIRS) {
    if (rel.startsWith(dir) || source + "/" === dir || source === dir.slice(0, -1)) return true;
  }
  for (const file of HOSTED_FILES) {
    if (source === file) return true;
  }
  if (HOSTED_TEST_FILES.includes(bare)) return true;
  for (const prefix of HOSTED_ROUTE_PREFIXES) {
    if (source === prefix || source.startsWith(prefix + ".") || source.startsWith(prefix + "/")) {
      return true;
    }
  }
  const locale = /^locales\/[^/]+\/([^/]+)\.json$/.exec(rel);
  if (locale && HOSTED_LOCALE_NAMESPACES.includes(locale[1])) return true;
  return false;
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (entry === "node_modules") continue;
      walk(full, out);
    } else if (/\.(tsx?|jsx?|mjs)$/.test(entry) && !entry.endsWith(".d.ts")) {
      out.push(full);
    }
  }
  return out;
}

/** Collect every static/dynamic import specifier in a source file. */
function importSpecifiers(source) {
  const specs = [];
  const patterns = [
    /\bimport\s+(?:type\s+)?[^'"()]*?\bfrom\s*['"]([^'"]+)['"]/g,
    /\bimport\s*['"]([^'"]+)['"]/g,
    /\bexport\s+(?:type\s+)?(?:\*|\{[^}]*\})\s*from\s*['"]([^'"]+)['"]/g,
    /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
    /\bimport\.meta\.glob\s*\(\s*['"]([^'"]+)['"]/g,
  ];
  for (const re of patterns) {
    let m;
    while ((m = re.exec(source))) specs.push(m[1]);
  }
  return specs;
}

/** Resolve a specifier to a src-relative posix path, or null when external. */
function resolveSpecifier(spec, fromFile) {
  let abs;
  if (spec.startsWith("@/")) abs = join(SRC, spec.slice(2));
  else if (spec.startsWith("./") || spec.startsWith("../")) abs = resolve(dirname(fromFile), spec);
  else return null;
  const rel = toPosix(relative(SRC, abs));
  if (rel.startsWith("..")) return null;
  return rel;
}

/** Point a bare specifier at a real file so `stores/credits` and `stores/credits.ts` agree. */
function withExtension(rel) {
  const abs = join(SRC, rel);
  if (existsSync(abs) && statSync(abs).isFile()) return rel;
  for (const ext of EXTENSIONS) {
    if (existsSync(abs + ext)) return rel + ext;
  }
  for (const ext of EXTENSIONS) {
    if (existsSync(join(abs, "index" + ext))) return rel + "/index" + ext;
  }
  return rel;
}

export function checkBoundary() {
  const offenders = [];
  for (const file of walk(SRC)) {
    const rel = toPosix(relative(SRC, file));
    if (SEAM_FILES.has(rel) || GENERATED_FILES.has(rel)) continue;
    if (isHostedPath(rel)) continue;
    const source = readFileSync(file, "utf8");
    // Typed i18n: the export drops the hosted locale files, so a core file that
    // reads a hosted namespace fails the exported typecheck. Catch it here.
    const nsRe = new RegExp("useTranslation\\(\\s*[\"'](" + HOSTED_LOCALE_NAMESPACES.join("|") + ")[\"']", "g");
    let nsMatch;
    while ((nsMatch = nsRe.exec(source))) {
      offenders.push({ file: rel, specifier: 'useTranslation("' + nsMatch[1] + '")', target: "locales/*/" + nsMatch[1] + ".json" });
    }
    for (const spec of importSpecifiers(source)) {
      const target = resolveSpecifier(spec, file);
      if (!target) continue;
      const resolved = withExtension(target);
      if (isHostedPath(resolved) || isHostedPath(target)) {
        offenders.push({ file: rel, specifier: spec, target: resolved });
      }
    }
  }
  return offenders;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const json = process.argv.includes("--json");
  const offenders = checkBoundary();
  if (json) {
    console.log(JSON.stringify(offenders, null, 2));
  } else if (offenders.length === 0) {
    console.log("edition boundary: OK (no core file imports a hosted path)");
  } else {
    console.error(`edition boundary: ${offenders.length} hosted import(s) from core files\n`);
    const byFile = new Map();
    for (const o of offenders) {
      if (!byFile.has(o.file)) byFile.set(o.file, []);
      byFile.get(o.file).push(o);
    }
    for (const [file, list] of [...byFile.entries()].sort()) {
      console.error(`  src/${file}`);
      for (const o of list) console.error(`      -> ${o.specifier}`);
    }
    console.error(
      "\nCore files may only reach hosted code through src/edition/slots.tsx." +
        "\nMove the file into a hosted directory, or route the import through the seam.",
    );
  }
  process.exit(offenders.length === 0 ? 0 : 1);
}
